from dataclasses import dataclass
from typing import Optional

import numpy as np
import pandas as pd


@dataclass
class CrowdConfig:
    """
    Configuration for crowd level analysis.

    All queue thresholds are example values.
    Replace them with actual terminal capacity and
    operationally approved thresholds.
    """

    terminal_capacity: int = 300

    low_max: float = 50
    moderate_max: float = 150
    high_max: float = 300

    # Crowd pressure warning levels
    moderate_pressure: float = 25
    high_pressure: float = 50
    critical_pressure: float = 100


class CrowdAnalysis:
    def __init__(self, config: Optional[CrowdConfig] = None):
        self.config = config or CrowdConfig()

        if self.config.terminal_capacity <= 0:
            raise ValueError("Terminal capacity must be greater than zero.")

        if not (
            0 <= self.config.low_max
            <= self.config.moderate_max
            <= self.config.high_max
        ):
            raise ValueError("Queue thresholds must be in ascending order.")

    def classify_crowd(self, queue_size):
        """
        Classify crowd level based on estimated queue size.
        """

        if queue_size < 0:
            raise ValueError("Queue size cannot be negative.")

        if queue_size <= self.config.low_max:
            return "Low"

        elif queue_size <= self.config.moderate_max:
            return "Moderate"

        elif queue_size <= self.config.high_max:
            return "High"

        return "Critical"

    def get_alert(self, crowd_level):
        """
        Generate operational alert from crowd level.
        """

        alerts = {
            "Low": "Normal",
            "Moderate": "Monitor crowd",
            "High": "Prepare crowd management",
            "Critical": "Immediate attention required",
        }

        return alerts.get(crowd_level, "Unknown")

    def analyze(self, queue_data: pd.DataFrame,
                queue_col: str = "queue_end") -> pd.DataFrame:
        """
        Analyze predicted queue data.

        Parameters
        ----------
        queue_data:
            DataFrame generated by queue_prediction.py.
        queue_col:
            Column containing predicted queue size.

        Returns
        -------
        DataFrame:
            Original queue data plus crowd classification,
            crowd pressure, and alerts.
        """

        if queue_col not in queue_data.columns:
            raise ValueError(
                f"Missing required queue column: {queue_col}"
            )

        result = queue_data.copy()

        queue = pd.to_numeric(
            result[queue_col],
            errors="coerce"
        )

        if queue.isna().any():
            raise ValueError(
                "Queue data contains missing or non-numeric values."
            )

        if (queue < 0).any():
            raise ValueError("Queue values cannot be negative.")

        # Crowd pressure as a percentage of terminal capacity
        result["crowd_pressure_pct"] = (
            queue / self.config.terminal_capacity
        ) * 100

        # Crowd classification
        result["crowd_level"] = queue.apply(
            self.classify_crowd
        )

        # Alert generation
        result["crowd_alert"] = result["crowd_level"].apply(
            self.get_alert
        )

        # Remaining terminal capacity
        result["remaining_capacity"] = (
            self.config.terminal_capacity - queue
        ).clip(lower=0)

        # Queue above assumed terminal capacity
        result["over_capacity"] = (
            queue > self.config.terminal_capacity
        )

        return result

    def get_summary(self, crowd_data: pd.DataFrame,
                    queue_col: str = "queue_end") -> dict:
        """
        Return summary metrics for the dashboard.
        """

        if crowd_data.empty:
            return {
                "peak_queue": 0,
                "peak_crowd_level": "No data",
                "peak_crowd_pressure_pct": 0,
                "critical_intervals": 0,
                "high_intervals": 0,
            }

        peak_index = crowd_data[queue_col].idxmax()
        peak_row = crowd_data.loc[peak_index]

        return {
            "peak_queue": int(peak_row[queue_col]),
            "peak_time": str(peak_index),
            "peak_crowd_level": peak_row["crowd_level"],
            "peak_crowd_pressure_pct": round(
                peak_row["crowd_pressure_pct"], 2
            ),
            "critical_intervals": int(
                (crowd_data["crowd_level"] == "Critical").sum()
            ),
            "high_intervals": int(
                (crowd_data["crowd_level"] == "High").sum()
            ),
        }
